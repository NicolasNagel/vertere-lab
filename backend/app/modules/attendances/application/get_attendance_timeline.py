"""Read the audit trail for one attendance — Fatia 5 of the attendance plan
checkpoint (`GET /attendances/{id}/timeline`). Pure read: no mutation, no
new audit entry generated by viewing it.

Permission is `attendances.read`, the same as `GET /attendances/{id}` —
this is a detail view of one attendance a user can already see, not the
broader "browse everything" audit screen (that would be `audit.read`,
out of scope here).
"""

from __future__ import annotations

from collections.abc import Collection
from dataclasses import dataclass, field, replace
from typing import Any, Protocol
from uuid import UUID

from app.modules.attendances.domain.repositories import AttendanceRepository
from app.modules.audit.domain.entities import AuditEntry
from app.modules.audit.domain.repositories import AuditLogReader
from app.shared.application.authorization import ActorContext
from app.shared.domain.errors import ForbiddenError, NotFoundError

_REQUIRED_PERMISSION = "attendances.read"
_ENTITY_TYPE = "attendance"


# Chaves de valor financeiro nos estados antes/depois da auditoria.
_MONEY_KEYS = frozenset(
    {
        "price_base",
        "discount_amount",
        "surcharge_amount",
        "total_amount",
        "subtotal",
        "discount_total",
        "surcharge_total",
        "on_call_fee",
        "urgency_fee",
        "clinic_fee",
        "fee_amount",
        "grand_total",
    }
)


def _without_money(value: Any) -> Any:
    if isinstance(value, dict):
        return {k: _without_money(v) for k, v in value.items() if k not in _MONEY_KEYS}
    if isinstance(value, list):
        return [_without_money(v) for v in value]
    return value


def _redact(entry: AuditEntry) -> AuditEntry:
    return replace(
        entry,
        before_state=_without_money(entry.before_state),
        after_state=_without_money(entry.after_state),
    )


class UserNameLookup(Protocol):
    def names_by_id(self, user_ids: Collection[UUID]) -> dict[UUID, str]: ...


@dataclass(frozen=True, kw_only=True)
class GetAttendanceTimelineQuery:
    actor: ActorContext
    attendance_id: UUID
    page: int
    page_size: int


@dataclass(frozen=True, kw_only=True)
class AttendanceTimelineResult:
    entries: list[AuditEntry]
    total: int
    page: int
    page_size: int
    # Só preenchido para quem não é de clínica (LAB/GLOBAL): usuário de clínica não vê nome de funcionário.
    actor_names: dict[UUID, str] = field(default_factory=dict)


class GetAttendanceTimelineUseCase:
    def __init__(
        self,
        *,
        attendances: AttendanceRepository,
        audit: AuditLogReader,
        user_names: UserNameLookup | None = None,
    ) -> None:
        self._attendances = attendances
        self._audit = audit
        self._user_names = user_names

    def execute(self, query: GetAttendanceTimelineQuery) -> AttendanceTimelineResult:
        if _REQUIRED_PERMISSION not in query.actor.permissions:
            raise ForbiddenError(f"Permissão ausente: {_REQUIRED_PERMISSION}")

        attendance = self._attendances.get_by_id(query.attendance_id)
        if attendance is None or not query.actor.can_access_clinic(attendance.clinic_id):
            raise NotFoundError("Atendimento não encontrado.")

        entries, total = self._audit.list_for_entity(
            entity_type=_ENTITY_TYPE,
            entity_id=str(attendance.id),
            page=query.page,
            page_size=query.page_size,
        )
        if "pricing.read" not in query.actor.permissions:
            entries = [_redact(entry) for entry in entries]
        names: dict[UUID, str] = {}
        if self._user_names is not None and query.actor.role_scope != "CLINIC":
            ids = {e.actor_user_id for e in entries if e.actor_user_id is not None}
            names = self._user_names.names_by_id(ids) if ids else {}
        return AttendanceTimelineResult(
            entries=entries,
            total=total,
            page=query.page,
            page_size=query.page_size,
            actor_names=names,
        )

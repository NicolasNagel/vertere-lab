"""Read the audit trail for one attendance — Fatia 5 of the attendance plan
checkpoint (`GET /attendances/{id}/timeline`). Pure read: no mutation, no
new audit entry generated by viewing it.

Permission is `attendances.read`, the same as `GET /attendances/{id}` —
this is a detail view of one attendance a user can already see, not the
broader "browse everything" audit screen (that would be `audit.read`,
out of scope here).
"""

from __future__ import annotations

from dataclasses import dataclass
from uuid import UUID

from app.modules.attendances.domain.repositories import AttendanceRepository
from app.modules.audit.domain.entities import AuditEntry
from app.modules.audit.domain.repositories import AuditLogReader
from app.shared.application.authorization import ActorContext
from app.shared.domain.errors import ForbiddenError, NotFoundError

_REQUIRED_PERMISSION = "attendances.read"
_ENTITY_TYPE = "attendance"


@dataclass(frozen=True, kw_only=True)
class GetAttendanceTimelineQuery:
    actor: ActorContext
    attendance_id: UUID
    page: int
    page_size: int


@dataclass(frozen=True, kw_only=True)
class AttendanceTimelineResult:
    entries: list[AuditEntry]
    total: int
    page: int
    page_size: int


class GetAttendanceTimelineUseCase:
    def __init__(
        self,
        *,
        attendances: AttendanceRepository,
        audit: AuditLogReader,
    ) -> None:
        self._attendances = attendances
        self._audit = audit

    def execute(self, query: GetAttendanceTimelineQuery) -> AttendanceTimelineResult:
        if _REQUIRED_PERMISSION not in query.actor.permissions:
            raise ForbiddenError(f"Permissão ausente: {_REQUIRED_PERMISSION}")

        attendance = self._attendances.get_by_id(query.attendance_id)
        if attendance is None:
            raise NotFoundError("Atendimento não encontrado.")

        entries, total = self._audit.list_for_entity(
            entity_type=_ENTITY_TYPE,
            entity_id=str(attendance.id),
            page=query.page,
            page_size=query.page_size,
        )
        return AttendanceTimelineResult(
            entries=entries, total=total, page=query.page, page_size=query.page_size
        )
